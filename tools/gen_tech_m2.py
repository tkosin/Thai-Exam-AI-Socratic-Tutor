def code(*lines):
    """รหัสลำลอง — ใช้ ← แทนการกำหนดค่า ตามที่หนังสือวิทยาการคำนวณใช้"""
    return '<div class="code">' + "\n".join(lines) + "</div>"


def M(unit, uname, sub, level, std, stem, choices, ans, why):
    """ข้อปรนัย 4 ตัวเลือก · ans ชี้ตำแหน่งตัวเลือกที่ถูกในลิสต์ต้นฉบับ (เขียนไว้ตัวแรกเสมอ)

    หมุนตำแหน่งด้วยลำดับข้อ ไม่ใช่การสุ่ม — ผลจึงเหมือนเดิมทุกครั้งที่รัน
    รหัสประจำข้อไม่ขยับ และเฉลยไม่กองอยู่ที่ ก ทั้งวิชา
    """
    if len(choices) != 4:
        fails.append(f"{stem[:40]}: ต้องมี 4 ตัวเลือก แต่มี {len(choices)}")
        return
    k = len(ITEMS) % 4
    opts = choices[-k:] + choices[:-k] if k else list(choices)
    pos = (ans + k) % 4
    if opts[pos] != choices[ans]:
        fails.append(f"{stem[:40]}: หมุนตัวเลือกแล้วเฉลยไม่ตรงตำแหน่ง")
    letters = "กขคง"
    body = "".join(f'<div class="ch"><b>{letters[i]}.</b> {c}</div>'
                   for i, c in enumerate(opts))
    ITEMS.append((unit, uname, sub, level, std,
                  stem + f'<div class="choices">{body}</div>', letters[pos], why))


def S(unit, uname, sub, level, std, text, answer, why):
    """ข้อเติมคำตอบ — เฉลยเป็นค่าเดียว ไม่กำกวม"""
    ITEMS.append((unit, uname, sub, level, std, text, str(answer), why))




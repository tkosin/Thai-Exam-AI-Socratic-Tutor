def audit():
    """ตรวจก่อนเขียนไฟล์ — ผิดข้อไหนก็ไม่เขียนเลย ดีกว่าเขียนครึ่งเดียวแล้วไปตายที่ด่านหลัง"""
    seen_std = {q[4] for q in ITEMS}
    for std in NEEDED:
        if std not in seen_std:
            fails.append(f"ตัวชี้วัด {std} ยังไม่มีข้อสอบสักข้อ")
    extra = sorted(seen_std - set(NEEDED) - {"-"})
    if extra:
        fails.append(f"มีตัวชี้วัดที่ไม่ใช่ของวิชานี้: {', '.join(extra)}")

    texts = set()
    for q in ITEMS:
        if q[5] in texts:
            fails.append(f"โจทย์ซ้ำ: {q[5][:60]}")
        texts.add(q[5])

    for sub, group in sorted(_by(2).items()):
        # กติกาข้อ 6 ของ olympiad-guide — แม่แบบที่มีไม่ถึง 8 ข้อ กรองแล้วใช้ฝึกไม่ได้
        if len(group) < 8:
            fails.append(f"แม่แบบ '{sub}' มีแค่ {len(group)} ข้อ ต้องมีอย่างน้อย 8")

    levels = {q[3] for q in ITEMS}
    # validate.py บังคับให้เทคโนโลยีมีครบทั้ง 5 ระดับ รวมโอลิมปิก
    for need in ("ง่าย", "กลาง", "ยาก", "แข่งขัน", "โอลิมปิก"):
        if need not in levels:
            fails.append(f"ยังไม่มีข้อระดับ '{need}'")

    top = sum(1 for q in ITEMS if q[3] in ("แข่งขัน", "โอลิมปิก"))
    share = top * 100.0 / len(ITEMS)
    if not 8 <= share <= 13:
        fails.append(f"สัดส่วนข้อสองระดับบน {share:.1f}% อยู่นอกช่วง 8–13% "
                     f"({top}/{len(ITEMS)} ข้อ)")

    # ---- กติกาเฟส 6: ทุกข้อต้องมีคำอธิบายที่อธิบายอะไรจริง ๆ ----
    for q in ITEMS:
        why = (q[7] or "").strip()
        if len(why) < 40:
            fails.append(f"คำอธิบายสั้นเกินไป ({len(why)} ตัวอักษร): {q[5][:50]}")

    # ---- กติกาเฟส 6: เฉลยต้องไม่เป็นตัวเลือกที่ยาวที่สุดบ่อยเกินไป ----
    # วิชานี้เปิด mcq_gate ตั้งแต่วันแรก ถ้าปล่อยให้เกิน check.sh จะไม่ผ่าน
    # ตรวจตรงนี้ด้วยเพื่อให้รู้ตั้งแต่ตอนเขียน ว่าตัวลวงข้อไหนสั้นเกินไป
    import re as _re
    mcq = [q for q in ITEMS if 'class="choices"' in q[5]]
    longest, worst = 0, []
    for q in mcq:
        opts = _re.findall(r'<div class="ch"><b>([ก-ง])\.</b>(.*?)</div>', q[5], _re.S)
        body = {k: _re.sub(r"<[^>]+>", "", v).strip() for k, v in opts}
        key = body[q[6]]
        if len(key) > max(len(v) for k, v in body.items() if k != q[6]):
            longest += 1
            worst.append(q[5][:44])
    rate = longest * 100.0 / len(mcq) if mcq else 0
    if rate > 40:
        fails.append(f"เฉลยเป็นตัวเลือกที่ยาวที่สุด {rate:.0f}% ({longest}/{len(mcq)}) "
                     f"เกิน 40% — เขียนตัวลวงให้ยาวพอกัน · เช่น {worst[0] if worst else ''}")
    return share, rate


def _by(idx):
    out = {}
    for q in ITEMS:
        out.setdefault(q[idx], []).append(q)
    return out


def write_units():
    os.makedirs(QDIR, exist_ok=True)
    by_unit = {}
    for unit, uname, sub, level, std, text, answer, why in ITEMS:
        by_unit.setdefault((unit, uname), []).append(
            {"text": text, "answer": answer, "sub": sub, "level": level,
             "std": std, "tag": "ม.2", "explain": why})
    for (unit, uname), qs in sorted(by_unit.items()):
        path = os.path.join(QDIR, UNIT_FILE[unit] + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump({"unit": unit, "uname": uname, "questions": qs},
                      f, ensure_ascii=False, indent=1)
            f.write("\n")
    return by_unit


def register():
    """ต่อวิชาเข้ากับ courses.json และเปลี่ยนหัวข้อใน topics.json เป็น active"""
    courses = json.load(open(COURSES, encoding="utf-8"))
    if not any(c["slug"] == "tech-m2" for c in courses):
        courses.append({
            "slug": "tech-m2", "subject": "เทคโนโลยี", "grade": "ม.2",
            "note": "หลักสูตรแกนกลาง 2551 (ปรับปรุง 2560) · สาระที่ 4 เทคโนโลยี "
                    "(ว 4.1 ออกแบบและเทคโนโลยี · ว 4.2 วิทยาการคำนวณ) "
                    "วิชาวิทยาศาสตร์ ม.2 ของคลังนี้ไม่ได้รวมสาระที่ 4 ไว้"})
        with open(COURSES, "w", encoding="utf-8") as f:
            json.dump(courses, f, ensure_ascii=False, indent=1)
            f.write("\n")

    doc = json.load(open(TOPICS, encoding="utf-8"))
    course = next((c for c in doc["courses"] if c["slug"] == "tech-m2"), None)
    if course is None:
        fails.append("ไม่พบรายวิชา tech-m2 ใน topics.json")
        return 0
    course["status"] = "active"
    n = 0
    for t in course["topics"]:
        if t["status"] != "active":
            t["status"] = "active"
            n += 1
    with open(TOPICS, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return n


def main():
    share, rate = audit()
    if fails:
        print("❌ ไม่เขียนไฟล์ เพราะตรวจไม่ผ่าน:")
        for f in fails:
            print("   -", f)
        return 1
    by_unit = write_units()
    flipped = register()
    print(f"เทคโนโลยี ม.2: {len(ITEMS)} ข้อ · {len(by_unit)} หน่วย · "
          f"ตัวชี้วัดครบ {len(NEEDED)} ตัว")
    for (unit, uname), qs in sorted(by_unit.items()):
        lv = {}
        for q in qs:
            lv[q["level"]] = lv.get(q["level"], 0) + 1
        print(f"   {unit}. {uname}: {len(qs)} ข้อ · "
              + " ".join(f"{k}:{v}" for k, v in lv.items()))
    mc = sum(1 for q in ITEMS if 'class="choices"' in q[5])
    print(f"ปรนัย {mc} ข้อ · เติมคำตอบเป็นตัวเลข {len(ITEMS) - mc} ข้อ "
          f"(ตรวจอัตโนมัติได้ทั้งหมด)")
    print(f"ข้อสองระดับบน {share:.1f}% · เฉลยเป็นตัวเลือกที่ยาวที่สุด {rate:.0f}% "
          f"· คำอธิบายครบ {len(ITEMS)}/{len(ITEMS)} ข้อ")
    print(f"เปลี่ยนหัวข้อเป็น active {flipped} ตัวชี้วัด")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def check(name, got, expect):
    """ยืนยันค่าที่จะใช้เป็นเฉลย ด้วยการคิดซ้ำอีกวิธีหนึ่ง"""
    if got != expect:
        fails.append(f"{name}: ทางแรกได้ {got} แต่คิดซ้ำได้ {expect}")
    return got


def num(v):
    """จำนวนเต็ม -> "12" · ทศนิยมลงตัว -> "0.75" · นอกนั้นเขียนเป็นเศษส่วนอย่างต่ำ "17/13"

    สเปกข้อ 4 ยอมรับคำตอบสามแบบนี้เท่านั้น ถ้าเป็นทศนิยมยาวเกินสองตำแหน่งแปลว่า
    ออกแบบตัวเลขผิด จึงบังคับให้เขียนเป็นเศษส่วนแทน ไม่ปัดทิ้ง
    """
    f = Fraction(v)
    if f.denominator == 1:
        return str(f.numerator)
    s = f"{float(f):.2f}".rstrip("0").rstrip(".")
    return s if Fraction(s) == f else f"{f.numerator}/{f.denominator}"


def add(slug, unit, text, answer, sub):
    ROWS.append((slug, unit, text, answer, sub))


def chain(*steps):
    """คูณต่อกันทีละขั้น — ใช้เป็นวิธีคิดซ้ำที่ไม่ใช่การยกกำลัง"""
    v = Fraction(1)
    for s in steps:
        v *= Fraction(s)
    return v



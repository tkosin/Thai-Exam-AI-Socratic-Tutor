    EXPR = {"sum2": ("&alpha;<sup>2</sup> + &beta;<sup>2</sup>", lambda p, q: p * p - 2 * q),
            "sum3": ("&alpha;<sup>3</sup> + &beta;<sup>3</sup>",
                     lambda p, q: p ** 3 - 3 * p * q),
            "diff2": ("(&alpha; - &beta;)<sup>2</sup>", lambda p, q: p * p - 4 * q),
            "inv": ("(1)/(&alpha;) + (1)/(&beta;)", lambda p, q: Fraction(p, q)),
            "mix": ("&alpha;<sup>2</sup>&beta; + &alpha;&beta;<sup>2</sup>",
                    lambda p, q: p * q)}
    for p_, q_, kind in SYM:
        label, fn = EXPR[kind]
        roots = [r for r in range(1, 200) if r * r - p_ * r + q_ == 0]
        if len(roots) != 2:
            fails.append(f"สมมาตรราก x^2-{p_}x+{q_}: รากไม่เป็นจำนวนเต็มสองราก")
            continue
        a, b = roots
        brute = {"sum2": a * a + b * b, "sum3": a ** 3 + b ** 3,
                 "diff2": (a - b) ** 2, "inv": Fraction(1, a) + Fraction(1, b),
                 "mix": a * a * b + a * b * b}[kind]
        v = check(f"สมมาตรราก {p_},{q_},{kind}", fn(p_, q_), brute)
        ans = frac(v.numerator, v.denominator) if isinstance(v, Fraction) else str(v)
        add(f"ถ้า &alpha; และ &beta; เป็นรากของสมการ x<sup>2</sup> - {p_}x + {q_} = 0 "
            f"จงหาค่าของ {label}", ans, "นิพจน์สมมาตรของรากสมการ", "-", "โอลิมปิก")

    # ── B. ความน่าจะเป็นเชิงนับจากลูกเต๋าสองลูก (แข่งขัน) ──
    OUT = [(a, b) for a in range(1, 7) for b in range(1, 7)]

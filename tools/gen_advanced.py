def check(name, got, expect):
    """ยืนยันค่าที่จะใช้เป็นเฉลย ด้วยการคิดซ้ำอีกวิธีหนึ่ง"""
    if got != expect:
        fails.append(f"{name}: สูตรได้ {got} แต่ไล่นับได้ {expect}")
    return got


def frac(n, d):
    f = Fraction(n, d)
    return f"{f.numerator}/{f.denominator}" if f.denominator != 1 else str(f.numerator)


# ---------------------------------------------------------------- ตัวช่วยเชิงตัวเลข
def digits_sum(n):
    return sum(int(c) for c in str(abs(n)))


def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def last_digit(base, exp):
    return pow(base, exp, 10)


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, math.isqrt(n) + 1))


def prime_factors(n):
    out, d = [], 2
    while d * d <= n:
        while n % d == 0:
            out.append(d)
            n //= d
        d += 1
    if n > 1:
        out.append(n)
    return out



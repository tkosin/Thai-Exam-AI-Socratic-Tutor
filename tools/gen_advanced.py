    for k in (45, 60, 96, 27, 72, 40, 21):
        pairs = [(a, b) for a in range(1, k + 2) for b in range(1, a)
                 if a * a - b * b == k]
        by_factor = [(d, k // d) for d in range(1, math.isqrt(k) + 1)
                     if k % d == 0 and (d + k // d) % 2 == 0 and k // d > d]
        check(f"a^2-b^2={k}", len(pairs), len(by_factor))
        add(f"ถ้า a และ b เป็นจำนวนเต็มบวกที่ a<sup>2</sup> - b<sup>2</sup> = {k} "
            "จะมีคู่อันดับ (a, b) ทั้งหมดกี่คู่", str(len(pairs)),
            "ผลต่างกำลังสองกับการนับคำตอบ", "-", "โอลิมปิก")

    # ── เศษจากการหารของเลขยกกำลัง (แข่งขัน) ──

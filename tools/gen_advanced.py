    add("มีจำนวนเต็ม x กี่จำนวนที่สอดคล้องกับอสมการ 2x - 3 &lt; 15 และ 3x + 4 &gt; 1 "
        "พร้อมกัน", str(v), "อสมการ")

    v = check("มัธยฐานของกำลังสอง", 25,
              sorted(k * k for k in range(1, 10))[4])
    add("นำจำนวนเต็มตั้งแต่ 1 ถึง 9 มายกกำลังสองทุกจำนวน จงหามัธยฐานของข้อมูลชุดใหม่",
        str(v), "สถิติ")

    v = check("จุดยอดพาราโบลา", -4, min(x * x + 4 * x for x in range(-10, 11)))

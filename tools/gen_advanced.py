def existing_texts():
    """โจทย์ทุกข้อที่มีอยู่แล้ว ยกเว้นหน่วยที่สคริปต์นี้เป็นคนเขียน (จะถูกเขียนทับอยู่แล้ว)"""
    import glob
    mine = {os.path.join(QDIR, slug, f"unit-{u:02d}-advanced.json")
            for slug, (u, _, _, _, _) in UNITS.items()}
    out = set()
    for path in glob.glob(os.path.join(QDIR, "*", "unit-*.json")):
        if path in mine:
            continue
        for q in json.load(open(path, encoding="utf-8"))["questions"]:
            out.add(q["text"])
    return out


def main():
    built = {slug: fn() for slug, (_, _, _, _, fn) in UNITS.items()}
    old = existing_texts()
    for slug, rows in built.items():
        for row in rows:
            if row[0] in old:
                fails.append(f"{slug}: โจทย์ซ้ำกับข้อที่มีอยู่แล้วในคลัง — {row[0][:60]}")
    if fails:
        print("❌ เฉลยที่คิดสองทางไม่ตรงกัน — ไม่เขียนไฟล์")
        for f in fails:
            print("   -", f)
        return 1

    for slug, (unit, uname, level, tag, _) in UNITS.items():
        rows = built[slug]
        seen, qs = set(), []
        for row in rows:
            text, answer, sub = row[0], row[1], row[2]
            std = row[3] if len(row) > 3 else "-"
            if text in seen:
                print(f"⚠️  {slug}: โจทย์ซ้ำ — {text[:40]}")
                continue
            seen.add(text)
            qs.append({"text": text, "answer": answer, "sub": sub, "level": level,
                       "std": std, "tag": tag})
        path = os.path.join(QDIR, slug, f"unit-{unit:02d}-advanced.json")
        json.dump({"unit": unit, "uname": uname, "questions": qs},
                  open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        open(path, "a", encoding="utf-8").write("\n")
        print(f"{slug}: หน่วย {unit} {uname} · {len(qs)} ข้อ ระดับ{level}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

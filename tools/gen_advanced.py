    for base, exp, mod in [(3, 200, 7), (2, 150, 5), (5, 120, 13),
                           (7, 100, 4), (4, 99, 9), (6, 80, 11), (9, 77, 8)]:
        # วัฏจักรจะวนกลับมาที่ค่าเดิมได้ต่อเมื่อฐานกับตัวหารเป็นจำนวนเฉพาะสัมพัทธ์
        if math.gcd(base, mod) != 1:
            fails.append(f"{base} กับ {mod} ไม่เป็นจำนวนเฉพาะสัมพัทธ์ วัฏจักรไม่วนกลับ")
            continue
        cycle, cur = [], base % mod
        while True:
            cycle.append(cur)
            cur = cur * base % mod
            if cur == cycle[0]:
                break
        brute = pow(base, exp, mod)
        v = check(f"{base}^{exp} mod {mod}", cycle[(exp - 1) % len(cycle)], brute)
        add(f"จงหาเศษที่ได้จากการหาร {base}<sup>{exp}</sup> ด้วย {mod}",
            str(v), "เศษจากการหารของเลขยกกำลัง", "-", "แข่งขัน")

    return q



def build(slug, subject, grade, prefix, rows, total, have, absent):
    if len(rows) != total:
        fails.append(f"{subject} {grade}: บันทึกได้ {len(rows)} ตัว แต่เอกสาร สพฐ. สรุปไว้ {total}")
    codes = {r[0].rsplit(" ", 1)[0] for r in rows}
    if codes != have:
        fails.append(f"{subject} {grade}: รหัสสาระที่พบ {sorted(codes)} "
                     f"ไม่ตรงกับที่ยืนยันไว้ {sorted(have)}")
    if codes & absent:
        fails.append(f"{subject} {grade}: พบรหัสสาระที่ยืนยันว่าไม่มีในชั้นนี้ "
                     f"{sorted(codes & absent)}")
    seen_std = set()
    topics = []
    for i, (std, text, strand, topic, svg) in enumerate(rows, 1):
        if std in seen_std:
            fails.append(f"{subject} {grade}: ตัวชี้วัด {std} ซ้ำ")
        seen_std.add(std)
        if f" {grade}/" not in std:
            fails.append(f"{std} ไม่ใช่ตัวชี้วัดของชั้น {grade}")
        # คำกริยาสั่งให้วาด/สร้างแบบจำลอง แต่ไม่ได้ตั้ง svg_type = พลาดแน่ ๆ
        hit = [v for v in FIG_VERBS if v in text]
        if hit and not svg:
            fails.append(f"{std}: ข้อความมีคำว่า '{hit[0]}' แต่ไม่ได้ตั้ง svg_type")
        topics.append({
            "id": f"{prefix}-{i:03d}",
            "std": std,
            "strand": strand,
            "topic": topic,
            "indicator": text,
            "needs_svg": bool(svg),
            "svg_type": svg,
            "status": "planned",
        })
    # official = ยอดที่เอกสารสรุปไว้ ติดไปกับข้อมูลเลย เพื่อให้ validate.py ตรวจซ้ำได้ทุกครั้ง
    # ไม่ใช่แค่ตอนรันสคริปต์นี้ครั้งเดียว (ถ้าใครมาลบ/เพิ่มตัวชี้วัดทีหลัง ด่านตรวจจะร้อง)
    return {"slug": slug, "subject": subject, "grade": grade,
            "status": "planned", "source": SOURCE,
            "official": {"total": total,
                         "std_present": sorted(have),
                         "std_absent": sorted(absent)},
            "topics": topics}


def main():
    doc = json.load(open(TOPICS, encoding="utf-8"))
    built = [build(*c) for c in COURSES]
    if fails:
        print("❌ ไม่เขียนไฟล์ เพราะตรวจไม่ผ่าน:")
        for f in fails:
            print("   -", f)
        return 1

    # รันซ้ำได้: ถ้ามีรายวิชานั้นแล้วให้เขียนทับด้วยของใหม่ ไม่ใช่ข้ามไปเงียบ ๆ
    # (ข้ามไปเงียบ ๆ = แก้ตารางในสคริปต์แล้วไฟล์ไม่เปลี่ยน ซึ่งหลอกคนแก้)
    by_key = {(c["subject"], c["grade"]): i for i, c in enumerate(doc["courses"])}
    added = []
    for c in built:
        key = (c["subject"], c["grade"])
        if key in by_key:
            # รักษา status เดิมไว้ — วิชาที่มีข้อสอบแล้วเป็น active ถ้าเขียนทับเป็น planned
            # ด่านตรวจจะร้องว่า "หัวข้อ planned ที่มีข้อสอบแล้ว" ทันที
            old = doc["courses"][by_key[key]]
            was = {t["std"]: t["status"] for t in old["topics"]}
            c["status"] = old.get("status", c["status"])
            for t in c["topics"]:
                t["status"] = was.get(t["std"], t["status"])
            doc["courses"][by_key[key]] = c
        else:
            doc["courses"].append(c)
            added.append(c)
    # วิชาที่ลงตัวชี้วัดแล้ว ต้องออกจาก planned_courses ไม่งั้นรายงานจะนับซ้ำ
    done = {(c["subject"], c["grade"]) for c in built}
    before = len(doc["planned_courses"])
    doc["planned_courses"] = [p for p in doc["planned_courses"]
                              if (p["subject"], p["grade"]) not in done]

    note = ("ตัวชี้วัด ป.5/ป.6 และเทคโนโลยี ม.3 บันทึกจากเอกสารสำนักวิชาการและมาตรฐาน"
            "การศึกษา สพฐ. ฉบับปรับปรุง 2560 · ฟิลด์ indicator เก็บข้อความเต็มแบบคัดลอกตรงตัว "
            "เพราะ needs_svg ตัดสินจากคำกริยาในตัวชี้วัด · ระดับประถมไม่มี ว 4.1 เลย "
            "(เริ่มมีตั้งแต่ ม.1) และ ค 1.3 กับ ค 3.2 ก็ไม่มีในประถมทุกชั้น")
    if note not in doc["_readme"]:
        doc["_readme"].append(note)

    with open(TOPICS, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")
    n = sum(len(c["topics"]) for c in built)
    print(f"เขียน {len(built)} รายวิชา (ใหม่ {len(added)}) · {n} ตัวชี้วัด ลง topics.json")
    print(f"planned_courses {before} -> {len(doc['planned_courses'])} วิชา")
    for c in added:
        fig = sum(1 for t in c["topics"] if t["needs_svg"])
        print(f"   {c['subject']} {c['grade']}: {len(c['topics'])} ตัวชี้วัด · ต้องมีรูป {fig}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def check(name, got, expect):
    if got != expect:
        fails.append(f"{name}: คิดสองวิธีได้ {got!r} กับ {expect!r} ไม่ตรงกัน")
    return got


def num(v):
    f = Fraction(v).limit_denominator(10 ** 6)
    if f.denominator == 1:
        return str(f.numerator)
    s = f"{float(f):.3f}".rstrip("0").rstrip(".")
    return s if Fraction(s) == f else f"{f.numerator}/{f.denominator}"


def add(slug, unit, uname, sub, level, std, text, answer, figure=None):
    row = {"text": text, "answer": str(answer), "sub": sub, "level": level,
           "std": std, "tag": "ป.5" if slug.endswith("p5") else "ป.6"}
    if figure:
        row["figure"] = figure
    ITEMS[slug].append((unit, uname, row))


def M(slug, unit, uname, sub, level, std, stem, choices, ans=0, figure=None):
    """ตัวเลือกที่ถูกเขียนไว้ตัวแรกเสมอเพื่อให้ตรวจทานง่าย แล้วหมุนตำแหน่งตอนสร้าง"""
    if len(choices) != 4:
        fails.append(f"{stem[:40]}: ต้องมี 4 ตัวเลือก แต่มี {len(choices)}")
    k = len(ITEMS[slug]) % 4
    opts = choices[-k:] + choices[:-k] if k else list(choices)
    pos = (ans + k) % 4
    if opts[pos] != choices[ans]:
        fails.append(f"{stem[:40]}: หมุนตัวเลือกแล้วเฉลยไม่ตรง")
    letters = "กขคง"
    body = "".join(f'<div class="ch"><b>{letters[i]}.</b> {c}</div>'
                   for i, c in enumerate(opts))
    add(slug, unit, uname, sub, level, std,
        stem + f'<div class="choices">{body}</div>', letters[pos], figure)


def S(slug, unit, uname, sub, level, std, text, answer, figure=None):
    add(slug, unit, uname, sub, level, std, text, answer, figure)


def block(slug, unit, sub, std, rows, figure_on=()):
    """rows = [(ระดับ, โจทย์, [4 ตัวเลือก โดยตัวแรกคือคำตอบ])] · figure_on = ดัชนีข้อที่ติดรูป

    std ใส่เป็นสตริงเดียว (ทั้งชุดอยู่ตัวชี้วัดเดียว) หรือเป็นลิสต์ยาวเท่าจำนวนข้อก็ได้
    ตัวชี้วัดวิทยาศาสตร์ชั้นประถมหลายตัวเป็นเรื่องเดียวกันแต่แยกเป็นคนละข้อ
    ถ้าบังคับให้หนึ่งชุดเท่ากับหนึ่งตัวชี้วัด จะได้ชุดละ 2-3 ข้อซึ่งต่ำกว่าเกณฑ์ 8 ข้อ
    """
    u, uname = unit
    figs = dict(figure_on)
    stds = [std] * len(rows) if isinstance(std, str) else list(std)
    if len(stds) != len(rows):
        fails.append(f"{sub}: ระบุตัวชี้วัด {len(stds)} ตัว แต่มี {len(rows)} ข้อ")
        return
    for i, (lv, stem, choices) in enumerate(rows):
        M(slug, u, uname, sub, lv, stds[i], stem, choices, 0, figs.get(i))



def audit(doc):
    for slug, rows in ITEMS.items():
        course = next((c for c in doc["courses"] if c["slug"] == slug), None)
        if course is None:
            fails.append(f"ไม่พบรายวิชา {slug} ใน topics.json")
            continue
        want = {t["std"] for t in course["topics"]}
        have = {r[2]["std"] for r in rows} - {"-"}
        if have - want:
            fails.append(f"{slug}: ใช้ตัวชี้วัดที่ไม่มีในแผนที่ {sorted(have - want)}")
        if want - have:
            fails.append(f"{slug}: ตัวชี้วัดที่ยังไม่มีข้อสอบ {sorted(want - have)}")
        # ตัวชี้วัดที่หลักสูตรสั่งให้มีรูป ต้องมีข้อที่ติดรูปจริงอย่างน้อยหนึ่งข้อ
        with_fig = {r[2]["std"] for r in rows if "figure" in r[2]}
        for t in course["topics"]:
            if t["needs_svg"] and t["std"] not in with_fig:
                fails.append(f"{slug}: ตัวชี้วัด {t['std']} ต้องมีรูป แต่ยังไม่มีข้อไหนติดรูป")

        seen = {}
        for _, _, r in rows:
            if r["text"] in seen:
                fails.append(f"{slug}: โจทย์ซ้ำ — {r['text'][:60]}")
            seen[r["text"]] = True
        per_sub = {}
        for _, _, r in rows:
            per_sub[r["sub"]] = per_sub.get(r["sub"], 0) + 1
        for sub, n in sorted(per_sub.items()):
            if n < 8:
                fails.append(f"{slug}: แม่แบบ '{sub}' มีแค่ {n} ข้อ ต้องมีอย่างน้อย 8")
        levels = {r["level"] for _, _, r in rows}
        for need in ("ง่าย", "กลาง", "ยาก", "แข่งขัน"):
            if need not in levels:
                fails.append(f"{slug}: ยังไม่มีข้อระดับ '{need}'")
        top = sum(1 for _, _, r in rows if r["level"] in ("แข่งขัน", "โอลิมปิก"))
        share = top * 100.0 / len(rows)
        if not 10 <= share <= 13:
            fails.append(f"{slug}: สัดส่วนข้อสองระดับบน {share:.1f}% นอกช่วง 10–13% "
                         f"({top}/{len(rows)})")


def write_units():
    out = {}
    for slug, rows in ITEMS.items():
        qdir = os.path.join(ROOT, "questions", slug)
        os.makedirs(qdir, exist_ok=True)
        by_unit = {}
        for unit, uname, r in rows:
            by_unit.setdefault((unit, uname), []).append(r)
        for (unit, uname), qs in sorted(by_unit.items()):
            path = os.path.join(qdir, UNIT_FILE[slug][unit] + ".json")
            with open(path, "w", encoding="utf-8") as f:
                json.dump({"unit": unit, "uname": uname, "questions": qs},
                          f, ensure_ascii=False, indent=1)
                f.write("\n")
        out[slug] = by_unit
    return out


def register(doc):
    courses = json.load(open(COURSES, encoding="utf-8"))
    known = {c["slug"] for c in courses}
    for slug in (P5, P6):
        subject, grade = COURSE_META[slug]
        if slug not in known:
            courses.append({"slug": slug, "subject": subject, "grade": grade,
                            "note": "หลักสูตรแกนกลาง 2551 (ปรับปรุง 2560) · ตัวชี้วัด ว · "
                                    "รวมสาระที่ 4 เทคโนโลยี (ว 4.2) ซึ่งชั้นประถม"
                                    "เรียนรวมอยู่ในวิชาวิทยาศาสตร์และเทคโนโลยี"})
    with open(COURSES, "w", encoding="utf-8") as f:
        json.dump(courses, f, ensure_ascii=False, indent=1)
        f.write("\n")
    n = 0
    for slug in (P5, P6):
        course = next(c for c in doc["courses"] if c["slug"] == slug)
        course["status"] = "active"
        for t in course["topics"]:
            if t["status"] != "active":
                t["status"] = "active"
                n += 1
    with open(TOPICS, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return n


def main():
    doc = json.load(open(TOPICS, encoding="utf-8"))
    audit(doc)
    if fails:
        print("❌ ไม่เขียนไฟล์ เพราะตรวจไม่ผ่าน:")
        for f in fails[:30]:
            print("   -", f)
        if len(fails) > 30:
            print(f"   … และอีก {len(fails) - 30} รายการ")
        return 1
    out = write_units()
    flipped = register(doc)
    for slug, by_unit in out.items():
        rows = ITEMS[slug]
        top = sum(1 for _, _, r in rows if r["level"] in ("แข่งขัน", "โอลิมปิก"))
        fig = sum(1 for _, _, r in rows if "figure" in r)
        print(f"{COURSE_META[slug][0]} {COURSE_META[slug][1]}: {len(rows)} ข้อ · "
              f"{len(by_unit)} หน่วย · สองระดับบน {top * 100.0 / len(rows):.1f}% · "
              f"ข้อที่มีรูป {fig}")
    print(f"เปลี่ยนหัวข้อเป็น active {flipped} ตัวชี้วัด")
    return 0


if __name__ == "__main__":
    sys.exit(main())

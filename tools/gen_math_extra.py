def write(slug, unit, uname, questions):
    path = os.path.join(Q, slug, f"unit-{unit:02d}-{uname}.json")
    name = {
        "constructions": "การสร้างทางเรขาคณิต",
        "competition-m1": "โจทย์ระดับแข่งขัน",
        "competition-m2": "โจทย์ระดับแข่งขัน",
    }[uname]
    seen, out = set(), []
    for x in questions:
        if x["text"] in seen:
            continue
        seen.add(x["text"])
        out.append(x)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump({"unit": unit, "uname": name, "questions": out},
                  fh, ensure_ascii=False, indent=1)
        fh.write("\n")
    lv = {}
    for x in out:
        lv[x["level"]] = lv.get(x["level"], 0) + 1
    order = ["ง่าย", "กลาง", "ยาก", "แข่งขัน"]
    print(f"  {slug}/หน่วย {unit} {name:<22} {len(out):>3} ข้อ · "
          + " ".join(f"{k}:{lv[k]}" for k in order if k in lv))



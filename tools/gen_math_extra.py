def frac(n, d):
    return f'<span class="frac"><span class="num">{n}</span><span class="den">{d}</span></span>'


def mc(stem, options, correct):
    letters = "กขคง"
    chs = "".join(f'<div class="ch"><b>{letters[i]}.</b> {o}</div>' for i, o in enumerate(options))
    return stem + f'<div class="choices">{chs}</div>', letters[correct]



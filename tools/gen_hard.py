def brute_sum(lo, hi):
    """ผลบวกจำนวนเต็มที่อยู่ *ระหว่าง* lo กับ hi — ไล่บวกทีละตัว"""
    return sum(k for k in range(lo + 1, hi))


def primes_between(lo, hi):
    out = []
    for k in range(lo + 1, hi):
        if k > 1 and all(k % d for d in range(2, int(k ** 0.5) + 1)):
            out.append(k)
    return out


def gcd_brute(a, b):
    return max(d for d in range(1, min(a, b) + 1) if a % d == 0 and b % d == 0)


def lcm_brute(a, b):
    for k in range(max(a, b), a * b + 1):
        if k % a == 0 and k % b == 0:
            return k
    raise AssertionError



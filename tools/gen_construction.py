#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""เพิ่มข้อ "คู่ขนาน" ที่ตรวจอัตโนมัติได้ ให้กับหน่วยการสร้างทางเรขาคณิตของ ม.1

หน่วย 4 ของ ม.1 มีข้อ "จงสร้าง …" อยู่ 15 ข้อที่เฉลยเป็นคำบรรยายขั้นตอนใช้วงเวียน
ผู้เรียนกดตรวจแล้วได้แค่ "ข้อนี้ตรวจอัตโนมัติไม่ได้" (ดู docs/recommendations.md ข้อ 2.3)

**ไม่แก้ข้อเดิม** — รหัสประจำข้อคิดจากแฮชของ text/figure/answer การแก้ข้อเดิมจะทำให้
ความก้าวหน้าของผู้เรียนหลุด สคริปต์นี้จึง *เพิ่ม* ข้อใหม่ที่ถามผลลัพธ์ของการสร้างเดียวกัน
เป็นตัวเลข ทุกทักษะใน 15 ข้อนั้นจึงมีข้อที่ตรวจได้จริงคู่กันอย่างน้อยหนึ่งข้อ

เฉลยทุกข้อคำนวณจากโค้ดในไฟล์นี้ และ check() คิดซ้ำอีกวิธีก่อนเขียนไฟล์
ถ้าสองทางไม่ตรงกัน สคริปต์หยุดทันที ไม่เขียนอะไรลงคลัง (แนวเดียวกับ gen_advanced.py)

รัน:  python3 tools/gen_construction.py && python3 tools/build.py
"""
import json
import math
import os
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from svg_helpers import BISECT_ANGLE_DEG        # noqa: E402 — ต้องตั้ง sys.path ก่อน

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QDIR = os.path.join(ROOT, "questions")
TARGET = os.path.join(QDIR, "math-m1", "unit-04-constructions.json")
STD = "ค 2.2 ม.1/1"

fails = []


def check(name, got, expect):
    """ยืนยันค่าที่จะใช้เป็นเฉลย ด้วยการคิดซ้ำอีกวิธีหนึ่ง"""
    if got != expect:
        fails.append(f"{name}: ทางแรกได้ {got} แต่คิดซ้ำได้ {expect}")
    return got


def n(v):
    """เลขที่จะเขียนลงเฉลย — จำนวนเต็มไม่ต้องมี .0 ห้อยท้าย"""
    f = Fraction(v)
    return str(f.numerator) if f.denominator == 1 else str(float(f))


def halve(v, k):
    """แบ่งครึ่งซ้ำ k ครั้ง — ไล่ทำจริง ไม่ใช้สูตร v/2^k"""
    for _ in range(k):
        v = Fraction(v, 2) if isinstance(v, int) else v / 2
    return v


def repeat_add(v, k):
    """ต่อกัน k ชุด — บวกซ้ำ ไม่ใช้การคูณ"""
    total = Fraction(0)
    for _ in range(k):
        total += v
    return total


ROWS = []          # (text, answer, sub, level, figure|None)


def add(text, answer, sub, level="กลาง", figure=None):
    ROWS.append((text, answer, sub, level, figure))


# ---------------------------------------------------------------- 1. ถ่ายความยาวด้วยวงเวียน
for a, k in ((7, 3), (9, 4), (12, 5)):
    ans = check(f"ถ่ายความยาว {a}x{k}", repeat_add(a, k), a * k)
    add(f"ใช้วงเวียนกางเท่ากับส่วนของเส้นตรง AB ที่ยาว {a} เซนติเมตร แล้วถ่ายความยาวนี้ "
        f"ต่อกันบนรังสีเดียวกัน {k} ครั้ง จะได้ส่วนของเส้นตรงยาวกี่เซนติเมตร",
        n(ans), "การสร้างทางเรขาคณิต", "ง่าย")

# ---------------------------------------------------------------- 2. แบ่งครึ่งและตั้งฉาก
for a in (18, 25):
    ans = check(f"ครึ่งของ {a}", Fraction(a, 2), halve(a, 1))
    add(f"สร้างเส้นแบ่งครึ่งและตั้งฉากกับส่วนของเส้นตรง AB ที่ยาว {a} เซนติเมตร "
        f"ด้วยวงเวียนและสันตรง เส้นที่สร้างได้ตัด AB ที่จุด M จงหาความยาว AM "
        f"เป็นเซนติเมตร", n(ans), "การสร้างทางเรขาคณิต")

# มุมที่เส้นแบ่งครึ่งตั้งฉากทำกับ AB — คิดจากมุมตรงที่ถูกแบ่งครึ่ง ไม่ใช่ท่องว่า 90
_straight = check("แบ่งครึ่งมุมตรง", halve(180, 1), Fraction(360, 4))
add("[[fig]]จากรูปการแบ่งครึ่งส่วนของเส้นตรง AB เส้น PQ ที่สร้างได้ทำมุมกับ AB กี่องศา",
    n(_straight), "การสร้างทางเรขาคณิต", "ง่าย", "m2-construct-bisect-segment")

# ---------------------------------------------------------------- 3. แบ่งครึ่งมุม
for d in (116, 74, 58):
    ans = check(f"ครึ่งของมุม {d}", Fraction(d, 2), halve(d, 1))
    add(f"แบ่งครึ่งมุม ABC ที่มีขนาด {d} องศา ด้วยวงเวียนและสันตรง "
        f"เส้นแบ่งครึ่งมุมทำมุมกับแขน BC กี่องศา", n(ans), "การสร้างทางเรขาคณิต")

# ค่ามุมต้องอ่านจากโค้ดที่วาดรูป ไม่ใช่พิมพ์เอง — เคยเจอปัญหารูปกับโจทย์เพี้ยนจากกันมาแล้ว
_abc = BISECT_ANGLE_DEG
add(f"[[fig]]จากรูปการแบ่งครึ่งมุม ABC ถ้ามุม ABC มีขนาด {_abc} องศา "
    f"จงหาขนาดของมุม FBC เป็นองศา",
    n(check(f"ครึ่งของมุม {_abc}", Fraction(_abc, 2), halve(_abc, 1))),
    "การสร้างทางเรขาคณิต", "ง่าย", "m2-construct-bisect-angle")

# ---------------------------------------------------------------- 4. สร้างมุม 60 ต่อกัน
for k in (2, 3):
    ans = check(f"มุม 60 ต่อกัน {k}", repeat_add(60, k), 60 * k)
    add(f"สร้างมุมขนาด 60 องศาด้วยวงเวียนและสันตรง แล้วสร้างต่อกันบนรังสีเดียวกัน "
        f"{k} มุม จะได้มุมรวมขนาดกี่องศา", n(ans), "การสร้างทางเรขาคณิต",
        "ง่าย" if k == 2 else "กลาง")

# ---------------------------------------------------------------- 5. แบ่งครึ่งมุมซ้ำ
for d, k in ((60, 1), (90, 1), (120, 2), (180, 2)):
    ans = check(f"แบ่งครึ่งมุม {d} จำนวน {k} ครั้ง", halve(d, k), Fraction(d, 2 ** k))
    add(f"สร้างมุมขนาด {d} องศา แล้วแบ่งครึ่งมุมด้วยวงเวียนและสันตรงติดต่อกัน {k} ครั้ง "
        f"จะได้มุมขนาดกี่องศา", n(ans), "การสร้างทางเรขาคณิต")

# ---------------------------------------------------------------- 6. แบ่งมุมตรงเท่า ๆ กัน
for k in (2, 3, 4):
    ans = check(f"แบ่งมุมตรงเป็น {k}", Fraction(180, k), Fraction(180) / k)
    add(f"แบ่งมุมตรงออกเป็น {k} ส่วนเท่า ๆ กันด้วยวงเวียนและสันตรง "
        f"แต่ละส่วนมีขนาดกี่องศา", n(ans), "การสร้างทางเรขาคณิต")

# ---------------------------------------------------------------- 7. เส้นตั้งฉากจากจุดนอกเส้น
add("[[fig]]จากรูปการสร้างเส้นตั้งฉากจากจุด P ที่อยู่นอกเส้นตรง เส้น PZ ที่สร้างได้ "
    "ทำมุมกับเส้นตรงกี่องศา", n(_straight), "การสร้างทางเรขาคณิต", "ง่าย",
    "m2-construct-perpendicular")

for h, r in ((5, 13), (8, 17), (9, 15)):
    half = math.isqrt(r * r - h * h)
    if half * half != r * r - h * h:
        fails.append(f"XY ของ (h={h} r={r}) ไม่เป็นจำนวนเต็ม")
    ans = check(f"XY ที่ h={h} r={r}", 2 * half,
                repeat_add(half, 2).numerator)      # คิดซ้ำด้วยการบวกซ้ำแทนการคูณ
    add(f"จุด P อยู่ห่างจากเส้นตรง L เป็นระยะ {h} เซนติเมตร กางวงเวียนจากจุด P "
        f"ด้วยรัศมี {r} เซนติเมตร ตัดเส้น L ที่จุด X และ Y จงหาความยาว XY "
        f"เป็นเซนติเมตร", n(ans), "การสร้างทางเรขาคณิต", "ยาก")

# ---------------------------------------------------------------- 8. เส้นขนานด้วยการคัดลอกมุม
for d in (63, 118):
    add(f"สร้างเส้นตรงผ่านจุด P ให้ขนานกับเส้นตรง L โดยคัดลอกมุมแย้ง "
        f"ถ้าเส้นตัดทำมุมกับเส้น L ขนาด {d} องศา "
        f"มุมที่ต้องคัดลอกไปสร้างที่จุด P มีขนาดกี่องศา",
        n(check(f"มุมแย้ง {d}", d, d)), "เส้นขนานและมุมที่เกี่ยวข้อง", "ง่าย")
    inner = check(f"มุมภายในข้างเดียวกัน {d}", 180 - d, Fraction(180 * (4 - 2), 2) - d)
    add(f"สร้างเส้นตรงผ่านจุด P ให้ขนานกับเส้นตรง L ถ้าเส้นตัดทำมุมกับเส้น L ขนาด {d} องศา "
        f"มุมภายในที่อยู่บนข้างเดียวกันของเส้นตัดที่จุด P มีขนาดกี่องศา",
        n(inner), "เส้นขนานและมุมที่เกี่ยวข้อง")

# ---------------------------------------------------------------- 9. สามเหลี่ยมด้านเท่า
for a in (6, 11):
    ans = check(f"รอบรูปสามเหลี่ยมด้านเท่า {a}", repeat_add(a, 3), 3 * a)
    add(f"สร้างรูปสามเหลี่ยมด้านเท่า ABC ให้มีด้านยาวเท่ากับส่วนของเส้นตรง XY "
        f"ที่ยาว {a} เซนติเมตร จงหาความยาวรอบรูปของสามเหลี่ยมที่ได้ เป็นเซนติเมตร",
        n(ans), "การสร้างรูปสามเหลี่ยม", "ง่าย")

# ---------------------------------------------------------------- 10. สามเหลี่ยมหน้าจั่ว
for base, leg in ((10, 13), (14, 9)):
    ans = check(f"รอบรูปหน้าจั่ว {base}/{leg}", base + repeat_add(leg, 2), base + 2 * leg)
    add(f"สร้างรูปสามเหลี่ยมหน้าจั่วที่มีฐานยาวเท่ากับ AB คือ {base} เซนติเมตร "
        f"และด้านประกอบมุมยอดยาวเท่ากับ CD คือ {leg} เซนติเมตร "
        f"จงหาความยาวรอบรูป เป็นเซนติเมตร", n(ans), "การสร้างรูปสามเหลี่ยม")

# ---------------------------------------------------------------- 11. คัดลอกมุม
for d, k in ((37, 2), (52, 3)):
    ans = check(f"คัดลอกมุม {d} จำนวน {k}", repeat_add(d, k), d * k)
    add(f"คัดลอกมุม ABC ที่มีขนาด {d} องศา ไปสร้างที่จุด P บนรังสี PQ ด้วยวงเวียนและสันตรง "
        f"แล้วสร้างมุมเท่ากันต่อกันจนครบ {k} มุม มุมรวมที่จุด P มีขนาดกี่องศา",
        n(ans), "การสร้างทางเรขาคณิต")

# ---------------------------------------------------------------- 12. สี่เหลี่ยมจัตุรัส
for a in (8, 15):
    peri = check(f"รอบรูปจัตุรัส {a}", repeat_add(a, 4), 4 * a)
    add(f"สร้างรูปสี่เหลี่ยมจัตุรัสที่มีด้านยาวเท่ากับส่วนของเส้นตรง AB คือ {a} เซนติเมตร "
        f"จงหาความยาวรอบรูป เป็นเซนติเมตร", n(peri),
        "การสร้างรูปสี่เหลี่ยมและสมบัติ", "ง่าย")
    area = check(f"พื้นที่จัตุรัส {a}", repeat_add(a, a), a * a)
    add(f"สร้างรูปสี่เหลี่ยมจัตุรัสที่มีด้านยาวเท่ากับส่วนของเส้นตรง AB คือ {a} เซนติเมตร "
        f"จงหาพื้นที่ เป็นตารางเซนติเมตร", n(area),
        "การสร้างรูปสี่เหลี่ยมและสมบัติ")

# ---------------------------------------------------------------- 13. แบ่งเส้นตรงด้วยการแบ่งครึ่งซ้ำ
for k in (2, 3):
    parts = check(f"แบ่งครึ่ง {k} ครั้ง", 2 ** k, int(1 / halve(1, k)))
    add(f"แบ่งครึ่งส่วนของเส้นตรง AB ด้วยวงเวียนและสันตรง แล้วแบ่งครึ่งแต่ละส่วนย่อยต่อไป "
        f"อีกจนครบ {k} รอบ จะได้ส่วนย่อยที่เท่ากันทั้งหมดกี่ส่วน", n(parts),
        "การนำการสร้างไปใช้")

for a, k in ((24, 2), (40, 3)):
    ans = check(f"ความยาวส่วนย่อย {a}/{k}", halve(Fraction(a), k), Fraction(a, 2 ** k))
    add(f"ส่วนของเส้นตรง AB ยาว {a} เซนติเมตร แบ่งครึ่งด้วยวงเวียนและสันตรงติดต่อกัน "
        f"{k} รอบ แต่ละส่วนย่อยยาวกี่เซนติเมตร", n(ans), "การนำการสร้างไปใช้")


def existing_texts():
    """ข้อความของทุกข้อในคลัง — กันไม่ให้เพิ่มข้อที่ซ้ำของเดิม"""
    seen = set()
    for course in json.load(open(os.path.join(QDIR, "courses.json"), encoding="utf-8")):
        import glob
        for path in glob.glob(os.path.join(QDIR, course["slug"], "unit-*.json")):
            for q in json.load(open(path, encoding="utf-8"))["questions"]:
                seen.add(q["text"].strip())
    return seen


def main():
    texts = [r[0] for r in ROWS]
    if len(set(texts)) != len(texts):
        fails.append("มีโจทย์ซ้ำกันเองในไฟล์นี้")
    dup = set(texts) & existing_texts()
    if dup:
        fails.append(f"โจทย์ซ้ำกับที่มีอยู่แล้ว {len(dup)} ข้อ เช่น {sorted(dup)[0][:60]}")
    if fails:
        print("❌ ไม่เขียนไฟล์ เพราะตรวจไม่ผ่าน:")
        for f in fails:
            print("   -", f)
        return 1

    data = json.load(open(TARGET, encoding="utf-8"))
    before = len(data["questions"])
    for text, answer, sub, level, figure in ROWS:
        q = {"text": text, "answer": answer, "sub": sub, "level": level,
             "std": STD, "tag": "ม.1"}
        if figure:
            q["figure"] = figure
        data["questions"].append(q)
    with open(TARGET, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"เพิ่ม {len(ROWS)} ข้อลง {os.path.relpath(TARGET, ROOT)} "
          f"({before} -> {len(data['questions'])} ข้อ)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

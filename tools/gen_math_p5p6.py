def grid_paths(w, h):
    """นับเส้นทางบนตาราง w×h ด้วยตารางสะสม ไม่ใช้สูตรการจัดหมู่"""
    g = [[1] * (w + 1) for _ in range(h + 1)]
    for i in range(1, h + 1):
        for j in range(1, w + 1):
            g[i][j] = g[i - 1][j] + g[i][j - 1]
    return g[h][w]


def comb(n, r):
    v = 1
    for i in range(r):
        v = v * (n - i) // (i + 1)
    return v



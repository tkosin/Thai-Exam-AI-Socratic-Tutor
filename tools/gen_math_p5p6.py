fails = []
ITEMS = {"math-p5": [], "math-p6": []}


def check(name, got, expect):
    if got != expect:
        fails.append(f"{name}: คิดสองวิธีได้ {got!r} กับ {expect!r} ไม่ตรงกัน")
    return got


def num(v):
    f = Fraction(v).limit_denominator(10 ** 7)
    if f.denominator == 1:
        return str(f.numerator)
    s = f"{float(f):.4f}".rstrip("0").rstrip(".")
    return s if Fraction(s) == f else f"{f.numerator}/{f.denominator}"


def fr(a, b):
    """เศษส่วนแบบที่คลังใช้ — verify_math อ่านกลับเป็น (a)/(b) ได้"""
    return (f'<span class="frac"><span class="num">{a}</span>'
            f'<span class="den">{b}</span></span>')


def mixed(w, a, b):
    return f"{w}{fr(a, b)}"


def M(slug, unit, uname, sub, level, std, stem, choices, ans, figure=None):
    """ปรนัย 4 ตัวเลือก — หมุนตำแหน่งเฉลยด้วยลำดับข้อ ไม่ให้เฉลยเป็น ก ทั้งวิชา"""
    if len(choices) != 4:
        fails.append(f"{stem[:40]}: ต้องมี 4 ตัวเลือก")
    k = len(ITEMS[slug]) % 4
    opts = choices[-k:] + choices[:-k] if k else list(choices)
    pos = (ans + k) % 4
    if opts[pos] != choices[ans]:
        fails.append(f"{stem[:40]}: หมุนตัวเลือกแล้วเฉลยไม่ตรง")
    letters = "กขคง"
    body = "".join(f'<div class="ch"><b>{letters[i]}.</b> {c}</div>'
                   for i, c in enumerate(opts))
    add(slug, unit, uname, sub, level, std,
        stem + f'<div class="choices">{body}</div>', letters[pos], figure)


def add(slug, unit, uname, sub, level, std, text, answer, figure=None):
    row = {"text": text, "answer": str(answer), "sub": sub,
           "level": level, "std": std, "tag": slug.split("-")[1].replace("p", "ป.")}
    if figure:
        row["figure"] = figure
    ITEMS[slug].append((unit, uname, row))


def S(slug, unit, uname, sub, level, std, text, answer, figure=None):
    add(slug, unit, uname, sub, level, std, text, answer, figure)



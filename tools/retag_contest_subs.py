def flat(slug):
    """{sub เดิม: ชื่อปลายทาง} — ฟ้องทันทีถ้ามี sub เดิมถูกแมปไปสองที่"""
    out = {}
    for dest, srcs in MAP[slug].items():
        out.setdefault(dest, dest)          # ชื่อปลายทางแมปหาตัวเอง ทำให้รันซ้ำได้
        for s in srcs:
            if s in out and out[s] != dest:
                raise SystemExit(f"{slug}: sub '{s}' ถูกแมปไปทั้ง '{out[s]}' และ '{dest}'")
            out[s] = dest
    return out


def main():
    changed, untouched = 0, collections.Counter()
    for slug in MAP:
        table = flat(slug)
        for path in sorted(glob.glob(os.path.join(QDIR, slug, "unit-*.json"))):
            data = json.load(open(path, encoding="utf-8"))
            hit = False
            for q in data["questions"]:
                if q["level"] not in LEVELS:
                    continue
                dest = table.get(q["sub"])
                if dest is None:
                    untouched[f"{slug} · {q['sub']}"] += 1
                elif dest != q["sub"]:
                    q["sub"] = dest
                    changed += 1
                    hit = True
            if hit:
                with open(path, "w", encoding="utf-8") as f:
                    json.dump(data, f, ensure_ascii=False, indent=1)
                    f.write("\n")
    print(f"เปลี่ยน sub ของข้อระดับแข่งขัน/โอลิมปิก {changed} ข้อ")
    if untouched:
        print(f"\nsub ที่ยังไม่ได้อยู่ในผัง {len(untouched)} ชื่อ "
              f"({sum(untouched.values())} ข้อ) — ต้องเพิ่มลง MAP หรือยืนยันว่าตั้งใจปล่อยไว้:")
        for k, v in untouched.most_common():
            print(f"   {v:>3}  {k}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

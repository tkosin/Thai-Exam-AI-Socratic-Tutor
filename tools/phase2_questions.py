def mc(items, two_col=False):
    cls = "choices two-col" if two_col else "choices"
    body = "".join(f'<div class="ch"><b>{k}.</b><span>{v}</span></div>'
                   for k, v in zip("กขคง", items))
    return f'<div class="{cls}">{body}</div>'


def frac(num, den, neg=False):
    return (("-" if neg else "") +
            f'<span class="frac"><span class="num">{num}</span>'
            f'<span class="den">{den}</span></span>')


def mixed(whole, num, den):
    return f'{whole}{frac(num, den)}'


def pw(base, exp):
    return f"{base}<sup>{exp}</sup>"


def xy_table(xs, ys, xl="x", yl="y"):
    head = "".join(f"<td>{v}</td>" for v in xs)
    body = "".join(f"<td>{v}</td>" for v in ys)
    return ('<table class="data-table">'
            f'<tr><th>{xl}</th>{head}</tr><tr><th>{yl}</th>{body}</tr></table>')



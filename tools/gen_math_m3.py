def quart(sorted_data, q):
    """ควอร์ไทล์แบบที่ใช้สอนใน ม.3 — ตำแหน่งที่ q(n+1)/4 เทียบสัดส่วนระหว่างสองค่า"""
    n = len(sorted_data)
    pos = Fraction(q * (n + 1), 4)
    lo = math.floor(pos)
    if lo < 1:
        return Fraction(sorted_data[0])
    if lo >= n:
        return Fraction(sorted_data[-1])
    frac_part = pos - lo
    return sorted_data[lo - 1] + frac_part * (sorted_data[lo] - sorted_data[lo - 1])



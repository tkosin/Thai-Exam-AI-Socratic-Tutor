def add(u, text, answer, sub, level, std=None, tag="ม.3", figure=None):
    q = {"text": text, "answer": str(answer), "sub": sub,
         "level": level, "std": std or u["std"], "tag": tag}
    if figure:                       # ชื่อรูปใน questions/figures.json · build.py แทรกให้
        q["figure"] = figure
    u["questions"].append(q)


def mc(stem, options, correct_idx):
    """ข้อปรนัย 4 ตัวเลือก -> (ข้อความโจทย์, ตัวอักษรเฉลย)"""
    letters = "กขคง"
    chs = "".join(f'<div class="ch"><b>{letters[i]}.</b> {o}</div>'
                  for i, o in enumerate(options))
    return stem + f'<div class="choices">{chs}</div>', letters[correct_idx]


def pick(seq, n):
    """สุ่มไม่ซ้ำ n ตัวจาก seq (ถ้าไม่พอก็คืนเท่าที่มี)"""
    s = list(seq)
    R.shuffle(s)
    return s[:n]



# เกณฑ์ที่ใช้กับแผนภาพกล่อง: ต่ำกว่า Q1 - 1.5·IQR หรือสูงกว่า Q3 + 1.5·IQR
# ใช้ N = 11 (N+1 หาร 4 ลงตัว) และคุมให้ IQR เป็นเลขคู่ ขอบเขตจึงเป็นจำนวนเต็ม
outl = []
while len(outl) < 4:
    core = sorted(RS.sample(range(20, 81), 11))
    q1, q3 = core[2], core[8]
    if (q3 - q1) % 2 or q3 - q1 < 12:
        continue
    outl.append(core)
for k, core in enumerate(outl):
    q1, q3 = core[2], core[8]
    iqr = q3 - q1
    low, high = q1 - 3 * iqr // 2, q3 + 3 * iqr // 2
    extras = [high + 2 + k, low - 3 - k] if k % 2 == 0 else [high + 5 + k]
    data = sorted(core + extras)
    txt = ", ".join(map(str, data))
    # ควอร์ไทล์ของชุดที่รวมค่าแปลกปลอมเข้าไปแล้วย่อมไม่ใช่ q1/q3 เดิม จึงบอกค่ามาให้ตรง ๆ

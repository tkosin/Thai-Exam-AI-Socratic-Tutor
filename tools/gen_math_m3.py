# ---------- ตัวช่วยจัดรูป ----------
def frac(n, d):
    """เศษส่วนแบบที่หน้าเว็บเรนเดอร์เป็นเศษ/ส่วนซ้อนกันจริง"""
    return f'<span class="frac"><span class="num">{n}</span><span class="den">{d}</span></span>'


def fr(f):
    """Fraction -> ข้อความเฉลย (จำนวนเต็มก็เขียนเป็นจำนวนเต็ม)"""
    f = Fraction(f)
    return str(f.numerator) if f.denominator == 1 else f"{f.numerator}/{f.denominator}"


def sup(base, e):
    return f"{base}<sup>{e}</sup>"


def poly(coeffs, var="x"):
    """[a, b, c] -> ax² + bx + c (ตัดพจน์ที่สัมประสิทธิ์เป็น 0 และจัดเครื่องหมายให้อ่านง่าย)"""
    deg = len(coeffs) - 1
    out = ""
    for i, c in enumerate(coeffs):
        p = deg - i
        if c == 0:
            continue
        sign = "-" if c < 0 else ("+" if out else "")
        a = abs(c)
        body = ("" if a == 1 and p else str(a)) + (var if p else "") + (f"<sup>{p}</sup>" if p > 1 else "")
        out += f" {sign} {body}" if out else f"{sign}{body}"
    return out or "0"


def signed(n):
    return f"+ {n}" if n >= 0 else f"- {abs(n)}"



def write():
    os.makedirs(OUT, exist_ok=True)
    slugs = {
        1: "inequalities", 2: "factoring-higher", 3: "quadratic-equations",
        4: "similarity", 5: "quadratic-graphs", 6: "linear-systems",
        7: "circles", 8: "pyramid-cone-sphere", 9: "probability",
        10: "statistics", 11: "trigonometry",
    }
    seen, total = set(), 0
    for u in UNITS:
        qs = []
        for q in u["questions"]:
            if q["text"] in seen:          # โจทย์ซ้ำทั้งคลังไม่ผ่าน validate.py
                continue
            seen.add(q["text"])
            qs.append(q)
        path = os.path.join(OUT, f"unit-{u['unit']:02d}-{slugs[u['unit']]}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump({"unit": u["unit"], "uname": u["uname"], "questions": qs},
                      fh, ensure_ascii=False, indent=1)
            fh.write("\n")
        lv = {}
        for q in qs:
            lv[q["level"]] = lv.get(q["level"], 0) + 1
        total += len(qs)
        order = ["ง่าย", "กลาง", "ยาก", "แข่งขัน"]
        print(f"  หน่วย {u['unit']:>2} {u['uname'][:34]:<34} {len(qs):>3} ข้อ · "
              + " ".join(f"{k}:{lv[k]}" for k in order if k in lv))
    print(f"\nรวม {total} ข้อ · {len(UNITS)} หน่วย")


if __name__ == "__main__":
    write()

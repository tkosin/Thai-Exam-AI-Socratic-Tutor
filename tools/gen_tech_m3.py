# เลือกกิจกรรมให้ได้จำนวนมากที่สุด — โลภด้วยเวลาสิ้นสุดที่เร็วที่สุด
ACTS = [(1, 4), (3, 5), (0, 6), (5, 7), (3, 9), (5, 9), (6, 10), (8, 11)]


def pick_activities(acts):
    end, n = -1, 0
    for s, e in sorted(acts, key=lambda t: t[1]):
        if s >= end:
            end, n = e, n + 1
    return n


def brute_activities(acts):
    """ไล่ทุกสับเซตแล้วหาชุดที่ใหญ่ที่สุดซึ่งไม่ทับซ้อนกัน — ช้าแต่ตรงนิยาม"""
    best = 0
    for mask in range(1 << len(acts)):
        chosen = sorted((acts[i] for i in range(len(acts)) if mask >> i & 1),
                        key=lambda t: t[0])
        if all(chosen[i][1] <= chosen[i + 1][0] for i in range(len(chosen) - 1)):
            best = max(best, len(chosen))
    return best



COINS = (10, 5, 2, 1)


def greedy_coins(amount, coins=COINS):
    used, left = 0, amount
    for c in coins:
        used += left // c
        left %= c
    return used


def fewest_coins(amount, coins=COINS):
    """คิดซ้ำด้วยการโปรแกรมพลวัต — ไม่ใช่วิธีโลภ จึงเป็นการตรวจคนละทางจริง ๆ"""
    best = [0] + [10**9] * amount
    for v in range(1, amount + 1):
        for c in coins:
            if c <= v:
                best[v] = min(best[v], best[v - c] + 1)
    return best[amount]



fails = []


def check(name, got, expect):
    """คิดคำตอบซ้ำด้วยวิธีที่สอง — ต่างวิธีแล้วยังได้เท่ากันจึงจะเชื่อได้"""
    if got != expect:
        fails.append(f"{name}: คิดด้วยสองวิธีได้ {got!r} กับ {expect!r} ไม่ตรงกัน")
    return got


def num(v):
    """จำนวนเต็ม -> "12" · ทศนิยมลงตัว -> "0.75" · นอกนั้นเป็นเศษส่วนอย่างต่ำ"""
    f = Fraction(v).limit_denominator(10**6)
    if f.denominator == 1:
        return str(f.numerator)
    s = f"{float(f):.3f}".rstrip("0").rstrip(".")
    return s if Fraction(s) == f else f"{f.numerator}/{f.denominator}"


def code(*lines):
    """รหัสลำลอง — ใช้ ← แทนการกำหนดค่า ตามที่หนังสือเรียนวิทยาการคำนวณใช้

    ไม่ใช้เครื่องหมาย < > ในรหัสลำลองเลย เพราะข้อความโจทย์ถูกวางเป็น HTML
    """
    return '<div class="code">' + "\n".join(lines) + "</div>"


ITEMS = []          # (unit, uname, sub, level, std, text, answer)


def M(unit, uname, sub, level, std, stem, choices, ans):
    """ข้อปรนัย 4 ตัวเลือก — ans เป็นเลข 0-3 ชี้ตัวเลือกที่ถูก ไม่ใช่ตัวอักษรที่พิมพ์เอง

    ในซอร์สเขียนตัวเลือกที่ถูกไว้ตัวแรกเสมอเพื่อให้ตรวจทานง่าย แล้วหมุนตำแหน่งตอนสร้าง
    ไม่งั้นเฉลยจะเป็น ก ทั้งวิชา ซึ่งผู้เรียนจับทางได้ตั้งแต่ข้อที่สาม
    หมุนด้วยลำดับข้อ ไม่ใช่การสุ่ม ผลลัพธ์จึงเหมือนเดิมทุกครั้งที่รัน (รหัสประจำข้อไม่ขยับ)
    """
    if len(choices) != 4:
        fails.append(f"{stem[:40]}: ต้องมี 4 ตัวเลือก แต่มี {len(choices)}")
    k = len(ITEMS) % 4
    opts = choices[-k:] + choices[:-k] if k else list(choices)
    pos = (ans + k) % 4
    if opts[pos] != choices[ans]:
        fails.append(f"{stem[:40]}: หมุนตัวเลือกแล้วเฉลยไม่ตรงตำแหน่ง")
    letters = "กขคง"
    body = "".join(f'<div class="ch"><b>{letters[i]}.</b> {c}</div>'
                   for i, c in enumerate(opts))
    ITEMS.append((unit, uname, sub, level, std,
                  stem + f'<div class="choices">{body}</div>', letters[pos]))


def S(unit, uname, sub, level, std, text, answer):
    """ข้อเติมคำตอบ — เฉลยเป็นค่าเดียว ไม่กำกวม"""
    ITEMS.append((unit, uname, sub, level, std, text, answer))


